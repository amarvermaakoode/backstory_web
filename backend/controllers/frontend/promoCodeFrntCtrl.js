const PromoCode = require("../../models/promoCode");
const ClaimCode = require("../../models/ClaimCode");

const defaultPromoCodes = [
  {
    code: "MARKETING",
    discountType: "percentage",
    discountValue: 100,
    minOrderAmount: 0,
    status: true,
  },
  {
    code: "WELCOME10",
    discountType: "percentage",
    discountValue: 10,
    minOrderAmount: 1000,
    status: true,
  },
  {
    code: "BACSTORY15",
    discountType: "percentage",
    discountValue: 15,
    minOrderAmount: 2000,
    status: true,
  },
  {
    code: "FLAT500",
    discountType: "flat",
    discountValue: 500,
    minOrderAmount: 3000,
    status: true,
  },
  {
    code: "BOGO",
    discountType: "percentage",
    discountValue: 50,
    minOrderAmount: 0,
    status: true,
  },
];

// get all active promo codes
const getActivePromoCodes = async (req, res) => {
  try {
    let promoCodes = await PromoCode.find({ status: true }).sort({ createdAt: -1 });

    // If no active promo codes exist in database, seed initial default promo codes
    if (!promoCodes || promoCodes.length === 0) {
      try {
        const totalInDb = await PromoCode.countDocuments();
        if (totalInDb === 0) {
          await PromoCode.insertMany(defaultPromoCodes);
          promoCodes = await PromoCode.find({ status: true }).sort({ createdAt: -1 });
        }
      } catch (seedErr) {
        console.error("Auto seed promo codes error:", seedErr.message);
        promoCodes = defaultPromoCodes;
      }
    }

    return res.status(200).json({
      success: true,
      count: promoCodes.length,
      data: promoCodes,
    });
  } catch (error) {
    return res.status(500).json({
      success: false,
      message: error.message,
    });
  }
};

// validate a promo code or marketing claim code
const validatePromoCode = async (req, res) => {
  try {
    const { code, orderAmount } = req.body;

    if (!code) {
      return res.status(400).json({
        success: false,
        message: "Promo code is required.",
      });
    }

    const cleanCode = code.trim().toUpperCase();

    // 1. Check in ClaimCode collection (Marketing / Gift claims generated by Admin)
    try {
      const claimDoc = await ClaimCode.findOne({
        code: cleanCode,
        type: { $in: ["MARKETING", "GIFT"] },
      });

      if (claimDoc) {
        if (claimDoc.status === "used") {
          return res.status(400).json({
            success: false,
            message: `This marketing claim code (${cleanCode}) has already been used.`,
          });
        }
        if (claimDoc.status === "revoked") {
          return res.status(400).json({
            success: false,
            message: `This marketing claim code (${cleanCode}) has been revoked.`,
          });
        }
        if (claimDoc.status === "expired" || (claimDoc.expiresAt && new Date() > new Date(claimDoc.expiresAt))) {
          return res.status(400).json({
            success: false,
            message: `This marketing claim code (${cleanCode}) has expired.`,
          });
        }

        // Valid Claim Code: 100% OFF free order
        return res.status(200).json({
          success: true,
          message: `Marketing claim code "${cleanCode}" applied! Bill is Rs 0 (100% OFF).`,
          data: {
            code: claimDoc.code,
            discountType: "percentage",
            discountValue: 100,
            minOrderAmount: 0,
            isMarketingCode: true,
            claimCodeId: claimDoc._id,
          },
        });
      }
    } catch (claimSearchErr) {
      console.error("Error searching ClaimCode:", claimSearchErr.message);
    }

    // 2. Check in PromoCode collection
    let promoCode = await PromoCode.findOne({ code: cleanCode });

    // Handle 0 vs O ambiguity (e.g. BOGO vs B0G0)
    if (!promoCode) {
      const swappedZeroToO = cleanCode.replace(/0/g, "O");
      const swappedOToZero = cleanCode.replace(/O/g, "0");
      promoCode = await PromoCode.findOne({
        $or: [{ code: swappedZeroToO }, { code: swappedOToZero }]
      });
    }

    // 3. Auto-seed MARKETING / FREE promo codes if entered
    if (!promoCode && ["MARKETING", "FREE", "BACFREE", "PROMO100"].includes(cleanCode)) {
      try {
        promoCode = await PromoCode.findOneAndUpdate(
          { code: cleanCode },
          {
            code: cleanCode,
            discountType: "percentage",
            discountValue: 100,
            minOrderAmount: 0,
            status: true,
          },
          { upsert: true, new: true }
        );
      } catch (upsertErr) {
        promoCode = {
          code: cleanCode,
          discountType: "percentage",
          discountValue: 100,
          minOrderAmount: 0,
          status: true,
        };
      }
    }

    // 4. Fallback to defaultPromoCodes
    if (!promoCode) {
      const defaultMatch = defaultPromoCodes.find((p) => p.code === cleanCode);
      if (defaultMatch) {
        promoCode = await PromoCode.create(defaultMatch);
      }
    }

    if (!promoCode || promoCode.status === false) {
      return res.status(404).json({
        success: false,
        message: "Invalid promo code. Try 'MARKETING' or check your code.",
      });
    }

    // Check if order amount is sufficient
    const subtotal = Number(orderAmount) || 0;
    if (subtotal < (promoCode.minOrderAmount || 0)) {
      return res.status(400).json({
        success: false,
        message: `This promo code requires a minimum order amount of Rs ${promoCode.minOrderAmount}.`,
      });
    }

    const is100Percent = promoCode.discountValue >= 100 || promoCode.code === "MARKETING";

    return res.status(200).json({
      success: true,
      message: is100Percent
        ? `Promo code "${promoCode.code}" applied! Bill is Rs 0 (100% OFF).`
        : "Promo code applied successfully.",
      data: {
        code: promoCode.code,
        discountType: is100Percent ? "percentage" : promoCode.discountType,
        discountValue: is100Percent ? 100 : promoCode.discountValue,
        minOrderAmount: promoCode.minOrderAmount || 0,
        isMarketingCode: is100Percent,
      },
    });
  } catch (error) {
    return res.status(500).json({
      success: false,
      message: error.message,
    });
  }
};

// Consume a claim code upon successful checkout
const consumeClaimCode = async (req, res) => {
  try {
    const { claimCodeId, code, orderId } = req.body || {};
    let claimDoc = null;

    if (claimCodeId) {
      claimDoc = await ClaimCode.findById(claimCodeId);
    }
    if (!claimDoc && code) {
      claimDoc = await ClaimCode.findOne({ code: String(code).trim().toUpperCase() });
    }

    if (claimDoc && claimDoc.status === "unused") {
      claimDoc.status = "used";
      claimDoc.claimedAt = new Date();
      if (req.user) {
        claimDoc.claimedBy = req.user.id || req.user._id;
      }
      if (orderId) {
        claimDoc.note = (claimDoc.note ? claimDoc.note + " | " : "") + `Used for Order #${orderId}`;
      }
      await claimDoc.save();
      console.log(`[ClaimCode] Successfully consumed marketing claim code ${claimDoc.code} for order ${orderId}`);
    }

    return res.status(200).json({
      success: true,
      message: "Claim code consumed successfully.",
    });
  } catch (err) {
    console.error("Error consuming claim code:", err);
    return res.status(500).json({
      success: false,
      message: err.message,
    });
  }
};

module.exports = {
  getActivePromoCodes,
  validatePromoCode,
  consumeClaimCode,
};

